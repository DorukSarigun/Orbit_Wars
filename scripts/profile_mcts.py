"""Profile abstract capture MCTS to find the real bottleneck.

Generates a realistic board via the actual orbit_wars env, builds an OrbitGraph,
then times CaptureMCTS.search() and cProfiles the hot path.
"""

from __future__ import annotations

import cProfile
import io
import pstats
import random
import sys
import time

from kaggle_environments import make

from orbit_graph import build_orbit_graph
from orbit_mcts import CaptureMCTS, MCTSConfig


def make_board(seed: int = 0):
    random.seed(seed)
    env = make("orbit_wars", debug=False)
    env.reset(num_agents=2)
    # Planets are generated by the interpreter on the first transition.
    env.step([[], []])
    obs = env.state[0]["observation"]
    return obs


def n_planets(obs) -> int:
    return len(obs["planets"])


def time_search(obs, sims: int, depth: int, reps: int = 20):
    og = build_orbit_graph(obs, player=0)
    cfg = MCTSConfig(simulations=sims, rollout_depth=depth)
    times = []
    for i in range(reps):
        mcts = CaptureMCTS(og, cfg, root_player=0, rng=random.Random(i))
        t0 = time.perf_counter()
        mcts.search()
        times.append((time.perf_counter() - t0) * 1000.0)
    times.sort()
    return times


def main():
    obs = make_board(0)
    print(f"planets on board: {n_planets(obs)}")

    for sims in (12, 24, 48):
        ts = time_search(obs, sims=sims, depth=4, reps=30)
        print(
            f"sims={sims:3d}  mean={sum(ts)/len(ts):7.2f}ms  "
            f"p50={ts[len(ts)//2]:7.2f}ms  max={ts[-1]:7.2f}ms"
        )

    print("\n--- build_orbit_graph cost ---")
    bt = []
    for _ in range(20):
        t0 = time.perf_counter()
        build_orbit_graph(obs, player=0)
        bt.append((time.perf_counter() - t0) * 1000.0)
    bt.sort()
    print(f"build_orbit_graph mean={sum(bt)/len(bt):7.2f}ms  max={bt[-1]:7.2f}ms")

    print("\n--- full agent.act() cost (per turn, build + MCTS) ---")
    from orbit_mcts_agent import OrbitMCTSAgent
    agent = OrbitMCTSAgent(mcts_cfg=MCTSConfig(simulations=24, rollout_depth=4))
    at = []
    for _ in range(20):
        t0 = time.perf_counter()
        agent.act(obs, player=0, current_turn=10, max_turns=500)
        at.append((time.perf_counter() - t0) * 1000.0)
    at.sort()
    print(f"act() sims=24 mean={sum(at)/len(at):7.2f}ms  max={at[-1]:7.2f}ms")

    print("\n--- cProfile full act() sims=24 ---")
    pr = cProfile.Profile()
    pr.enable()
    for _ in range(20):
        agent.act(obs, player=0, current_turn=10, max_turns=500)
    pr.disable()
    s = io.StringIO()
    pstats.Stats(pr, stream=s).sort_stats("tottime").print_stats(22)
    print(s.getvalue())


if __name__ == "__main__":
    sys.exit(main())
